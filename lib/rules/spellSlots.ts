export function fullCasterSlots(level: number): SlotsByLevel {
  return FULL_CASTER_SLOTS[Math.min(level, 20)] ?? FULL_CASTER_SLOTS[0];
}

export function halfCasterSlots(level: number): SlotsByLevel {
  return HALF_CASTER_SLOTS[Math.min(level, 20)] ?? HALF_CASTER_SLOTS[0];
}

export function warlockPactMagic(level: number): { slots: number; slotLevel: number } {
  const [slots, slotLevel] = WARLOCK_PACT_MAGIC[Math.min(level, 20)] ?? [0, 0];
  return { slots, slotLevel };
}
